class DraftedQuestion(BaseModel):
    """One LLM-drafted question for one document (schema for the LLM call)."""

    question: str
    language: Literal["pt", "en"]
    category: Literal["factual", "table", "language"]
    expected_pages: list[int] = Field(default_factory=list)
    reference_answer: str


class DocumentDraft(BaseModel):
    """1-2 drafted questions for one document."""

    questions: list[DraftedQuestion] = Field(min_length=1, max_length=2)


class NoAnswerQuestion(BaseModel):
    """One drafted question whose answer the corpus does not contain."""

    question: str
    language: Literal["pt", "en"]


class NoAnswerDraft(BaseModel):
    """The fixed-size no-answer slice (schema for the LLM call)."""

    questions: list[NoAnswerQuestion] = Field(min_length=N_NO_ANSWER, max_length=N_NO_ANSWER)


@dataclass
class DocInfo:
    """Inventory record of one indexed document (no chunk text)."""

    doc_id: int
    version_id: int
    path: str
    title: str | None
    format: str
    language: str | None
    folder: str
    n_chunks: int = 0
    token_count: int = 0
    paged: bool = False
    chunk_langs: set[str] = field(default_factory=set)
    tags: list[str] = field(default_factory=list)

    @property
    def lang_bucket(self) -> str:
        """Effective language: per-chunk pt/en, ``mixed`` when both, else unknown."""
        langs = {lang for lang in self.chunk_langs if lang in LANGS}
        if len(langs) > 1:
            return "mixed"
        if langs:
            return next(iter(langs))
        return self.language if self.language in LANGS else "unknown"


@dataclass
class ChunkRow:
    """The chunk fields the excerpt sampler needs."""

    ordinal: int
    text: str
    page: int | None
    slide: int | None
    section: str | None
    heading_path: list[str]
    is_table: bool


def collect_documents(session: Any) -> list[DocInfo]:
    """Collect the inventory of current documents with latest-version stats.

    Args:
        session: An open SQLAlchemy session.

    Returns:
        One :class:`DocInfo` per current document, ordered by rel path.
    """
    rows = session.execute(
        select(
            Document.id,
            Document.latest_version_id,
            Document.title,
            Document.format,
            Document.language,
            File.rel_path,
        )
        .join(File, Document.current_file_id == File.id)
        .where(Document.status == "current", Document.latest_version_id.is_not(None))
        .order_by(File.rel_path)
    ).all()
    version_ids = [row.latest_version_id for row in rows]

    agg: dict[int, dict[str, Any]] = defaultdict(
        lambda: {"n": 0, "tokens": 0, "paged": False, "langs": set()}
    )
    tag_map: dict[int, list[str]] = {}
    if version_ids:
        chunk_rows = session.execute(
            select(
                Chunk.document_id,
                Chunk.language,
                func.count(),
                func.sum(Chunk.token_count),
                func.bool_or(Chunk.page.is_not(None)),
                func.bool_or(Chunk.slide.is_not(None)),
            )
            .where(Chunk.document_version_id.in_(version_ids))
            .group_by(Chunk.document_id, Chunk.language)
        ).all()
        for doc_id, lang, n, tokens, has_page, has_slide in chunk_rows:
            cell = agg[doc_id]
            cell["n"] += int(n)
            cell["tokens"] += int(tokens or 0)
            cell["paged"] = cell["paged"] or bool(has_page or has_slide)
            if lang:
                cell["langs"].add(lang)
        # Same computation as index.documents.document_index_tags, but only
        # the small frontmatter/hashtags columns are transferred.
        tag_rows = session.execute(
            select(
                DocumentVersion.id,
                DocumentVersion.frontmatter,
                cast(DocumentVersion.ir_json["hashtags"], Text),
            ).where(DocumentVersion.id.in_(version_ids))
        ).all()
        for version_id, frontmatter, hashtags_text in tag_rows:
            try:
                hashtags = json.loads(hashtags_text) if hashtags_text else []
            except json.JSONDecodeError:
                logger.warning("unparseable hashtags on version %s; ignoring", version_id)
                hashtags = []
            tag_map[version_id] = manual_tags(frontmatter or {}, hashtags or [])

    docs: list[DocInfo] = []
    for row in rows:
        cell = agg.get(row.id, {"n": 0, "tokens": 0, "paged": False, "langs": set()})
        docs.append(
            DocInfo(
                doc_id=row.id,
                version_id=row.latest_version_id,
                path=row.rel_path,
                title=row.title,
                format=row.format,
                language=row.language,
                folder=row.rel_path.split("/")[0] if "/" in row.rel_path else "(root)",
                n_chunks=int(cell["n"]),
                token_count=int(cell["tokens"]),
                paged=bool(cell["paged"]),
                chunk_langs=set(cell["langs"]),
                tags=tag_map.get(row.latest_version_id, []),
            )
        )
    return docs


def load_chunks(session: Any, docs: Sequence[DocInfo]) -> dict[int, list[ChunkRow]]:
    """Load the latest-version chunks of the given documents, ordered by ordinal.

    Args:
        session: An open SQLAlchemy session.
        docs: The documents whose chunks to load.

    Returns:
        ``{doc_id: [ChunkRow, ...]}``; documents without chunks are absent.
    """
    version_ids = [doc.version_id for doc in docs]
    if not version_ids:
        return {}
    rows = session.execute(
        select(
            Chunk.document_id,
            Chunk.ordinal,
            Chunk.text,
            Chunk.page,
            Chunk.slide,
            Chunk.section,
            Chunk.heading_path,
            Chunk.is_table,
        )
        .where(Chunk.document_version_id.in_(version_ids))
        .order_by(Chunk.document_id, Chunk.ordinal)
    ).all()
    result: dict[int, list[ChunkRow]] = defaultdict(list)
    for doc_id, ordinal, text, page, slide, section, heading_path, is_table in rows:
        result[doc_id].append(
            ChunkRow(
                ordinal=ordinal,
                text=text,
                page=page,
                slide=slide,
                section=section,
                heading_path=list(heading_path or []),
                is_table=bool(is_table),
            )
        )
    return dict(result)


def stratified_pick(
    docs: Sequence[DocInfo], n: int, rng: random.Random, key: Callable[[DocInfo], Any]
) -> list[DocInfo]:
    """Pick up to ``n`` documents round-robin over the buckets of ``key``.

    Args:
        docs: Candidate documents (one entry per document).
        n: How many documents to pick.
        rng: Seeded random source (shuffles within buckets).
        key: Bucket key per document (folder, format, language, ...).

    Returns:
        The picked documents; fewer than ``n`` when candidates run out.
    """
    buckets: dict[Any, list[DocInfo]] = defaultdict(list)
    for doc in docs:
        buckets[key(doc)].append(doc)
    for members in buckets.values():
        rng.shuffle(members)
    bucket_keys = sorted(buckets, key=str)
    picked: list[DocInfo] = []
    while len(picked) < n:
        progressed = False
        for bucket_key in bucket_keys:
            members = buckets[bucket_key]
            if members and len(picked) < n:
                picked.append(members.pop(0))
                progressed = True
        if not progressed:
            break
    return picked


def assign_cross_lingual(picked: Sequence[DocInfo], n: int = N_CROSS_LINGUAL) -> dict[int, str]:
    """Choose which drafted questions switch language (cross-lingual slice).

    EN documents get their question written in PT (the direction the M0 check
    flagged as harder); any remaining slots flip PT documents to EN.

    Args:
        picked: The documents queued for drafting, in pick order.
        n: How many cross-lingual questions to assign.

    Returns:
        ``{doc_id: question_language}`` for the assigned documents only.
    """
    assignment: dict[int, str] = {}
    for flip_from, flip_to in (("en", "pt"), ("pt", "en")):
        for doc in picked:
            if len(assignment) >= n:
                return assignment
            if doc.lang_bucket == flip_from:
                assignment[doc.doc_id] = flip_to
    return assignment


def render_excerpt(chunk: ChunkRow) -> str:
    """Render one chunk as a labelled excerpt for the drafting prompt.

    Args:
        chunk: The chunk to render.

    Returns:
        The excerpt text, truncated, with page/slide and section labels.
    """
    labels: list[str] = []
    if chunk.page is not None:
        labels.append(f"page {chunk.page}")
    elif chunk.slide is not None:
        labels.append(f"slide {chunk.slide}")
    heading = " > ".join(chunk.heading_path) if chunk.heading_path else chunk.section
    if heading:
        labels.append(f"section: {heading}")
    text = " ".join(chunk.text[:EXCERPT_CHARS].split())
    return f"[{' | '.join(labels)}]\n{text}" if labels else text


def select_excerpts(chunks: Sequence[ChunkRow], max_n: int = N_EXCERPTS) -> list[str]:
    """Sample up to ``max_n`` content-bearing excerpts spread across a document.

    Args:
        chunks: The document's chunks in ordinal order.
        max_n: Maximum number of excerpts.

    Returns:
        Rendered excerpts; empty when no chunk carries enough text.
    """
    if not chunks:
        return []
    if len(chunks) <= max_n:
        candidates = list(chunks)
    elif max_n <= 1:
        candidates = [chunks[0]]
    else:
        last = len(chunks) - 1
        candidates = [chunks[round(i * last / (max_n - 1))] for i in range(max_n)]
        unique: list[ChunkRow] = []
        for chunk in candidates:
            if all(chunk is not seen for seen in unique):
                unique.append(chunk)
        candidates = unique
    excerpts = [render_excerpt(c) for c in candidates if len(c.text.split()) >= MIN_EXCERPT_WORDS]
    if len(excerpts) < max_n:
        chosen = {id(c) for c in candidates}
        for chunk in chunks:
            if len(excerpts) >= max_n:
                break
            if id(chunk) in chosen or len(chunk.text.split()) < MIN_EXCERPT_WORDS:
                continue
            excerpts.append(render_excerpt(chunk))
    return excerpts[:max_n]


def question_row(
    info: DocInfo, drafted: DraftedQuestion, cross_lang: str | None, tag_pick: bool
) -> dict[str, Any]:
    """Build one golden-set question dict from a drafted question.

    Args:
        info: The source document.
        drafted: The parsed LLM answer.
        cross_lang: Question language when this is a cross-lingual question.
        tag_pick: Whether this question carries an explicit tag filter.

    Returns:
        The golden-set question dict (without the id).
    """
    row: dict[str, Any] = {
        "question": drafted.question.strip(),
        "language": cross_lang or drafted.language,
        "category": "language" if cross_lang else drafted.category,
        "tags": ["draft", "cross-lingual"] if cross_lang else ["draft"],
        "filters": {
            "tags": [info.tags[0]] if tag_pick and info.tags else [],
            "folders": [],
        },
        "expected_docs": [info.path],
        "reference_answer": drafted.reference_answer.strip(),
    }
    if tag_pick:
        row["category"] = "tag-filtered"
    pages = [int(p) for p in drafted.expected_pages if p and p > 0] if info.paged else []
    if pages:
        row["expected_pages"] = sorted(set(pages))
    return row


def q_language_instruction(info: DocInfo, cross_lang: str | None) -> str:
    """The question-language rule for one document's drafting prompt.

    Args:
        info: The source document.
        cross_lang: Question language for cross-lingual questions, else None.

    Returns:
        Human-readable instruction embedded in the prompt.
    """
    if cross_lang == "pt":
        return 'European Portuguese ("pt") - cross-lingual check: the source document is in English'
    if cross_lang == "en":
        return 'English ("en") - cross-lingual check: the source document is in Portuguese'
    if info.lang_bucket == "pt":
        return 'European Portuguese ("pt")'
    if info.lang_bucket == "en":
        return 'English ("en")'
    return 'the language of the excerpt the question comes from ("pt" or "en")'


def draft_document(
    chat: ChatModel,
    chunks: Sequence[ChunkRow],
    info: DocInfo,
    cross_lang: str | None,
    tag_pick: bool,
) -> tuple[list[dict[str, Any]], str | None]:
    """Draft 1-2 questions for one document.

    Args:
        chat: The chat model (used at background priority).
        chunks: The document's latest-version chunks.
        info: The source document.
        cross_lang: Question language for cross-lingual questions, else None.
        tag_pick: Whether the question gets an explicit tag filter.

    Returns:
        ``(question_dicts, error)``; ``error`` is None on success and the
        question list is empty when the document has no usable excerpts.
    """
    excerpts = select_excerpts(chunks)
    if not excerpts:
        return [], "no usable excerpts"
    prompt = DOCUMENT_PROMPT.format(
        path=info.path,
        title=info.title or info.path,
        format=info.format,
        excerpts="\n\n".join(excerpts),
        q_language=q_language_instruction(info, cross_lang),
        pages_rule=(
            '- For every question set "expected_pages" to the page number(s) '
            "(from the excerpt labels) where the answer appears.\n"
            if info.paged
            else '- This document has no page numbers: always leave "expected_pages" empty.\n'
        ),
    )
    messages = [ChatMessage(role="user", content=prompt)]
    try:
        parsed = complete_structured(chat, messages, DocumentDraft, priority="background")
    except (StructuredOutputError, EndpointError) as exc:
        logger.warning("%s: drafting failed: %s", info.path, exc)
        return [], str(exc)
    return [question_row(info, q, cross_lang, tag_pick) for q in parsed.questions[:2]], None


def draft_no_answer(chat: ChatModel, titles: Sequence[str]) -> list[dict[str, Any]]:
    """Draft the no-answer questions (topics absent from the corpus).

    Args:
        chat: The chat model (used at background priority).
        titles: One ``path - title`` line per corpus document.

    Returns:
        The no-answer question dicts (empty when the call fails).
    """
    prompt = NO_ANSWER_PROMPT.format(titles="\n".join(titles), n=N_NO_ANSWER)
    messages = [ChatMessage(role="user", content=prompt)]
    try:
        parsed = complete_structured(chat, messages, NoAnswerDraft, priority="background")
    except (StructuredOutputError, EndpointError) as exc:
        logger.warning("no-answer drafting failed: %s", exc)
        return []
    return [
        {
            "question": q.question.strip(),
            "language": q.language,
            "category": "no-answer",
            "tags": ["draft"],
            "filters": {"tags": [], "folders": []},
        }
        for q in parsed.questions
    ]


def write_draft(out: Path, questions: list[dict[str, Any]], extra_meta: dict[str, Any]) -> None:
    """Write the draft YAML with the review header.

    Args:
        out: Output path (parent directories are created).
        questions: The assembled question dicts (ids are assigned here).
        extra_meta: Generation parameters to record under ``meta``.
    """
    numbered = [dict(id=f"d{i + 1:03d}", **row) for i, row in enumerate(questions)]
    counts = Counter(row["category"] for row in numbered)
    meta = {
        "created": datetime.now(UTC).date().isoformat(),
        "corpus_note": "DRAFT for human review (task 32 Part A); save the reviewed "
        "set as eval/golden_set.yaml before running Part B.",
        "counts": {name: counts[name] for name in sorted(counts)},
        **extra_meta,
    }
    body = yaml.safe_dump(
        {"meta": meta, "questions": numbered}, allow_unicode=True, sort_keys=False
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER_COMMENT + body, encoding="utf-8")
    console.print(f"[green]Wrote {len(numbered)} draft questions to[/] {out}")
    console.print_json(json.dumps(meta["counts"]))
    console.print(
        "Now review the draft (see the header checklist) and save it as "
        "eval/golden_set.yaml; Part B needs the reviewed file."
    )


def list_docs() -> None:
    """Print the indexed document inventory as a Rich table."""
    with session_scope() as session:
        docs = collect_documents(session)
    if not docs:
        console.print("[yellow]No current documents found - run `mynotes scan` first.[/]")
        return
    table = Table(title=f"{len(docs)} indexed documents", show_lines=False)
    for column in ("Path", "Title", "Format", "Language", "Chunks", "Folder", "Tags"):
        table.add_column(column, overflow="fold")
    for doc in docs:
        language = doc.language or "?"
        if doc.lang_bucket == "mixed":
            language += " (mixed)"
        table.add_row(
            doc.path,
            (doc.title or "")[:TITLE_CHARS],
            doc.format,
            language,
            str(doc.n_chunks),
            doc.folder,
            ", ".join(doc.tags[:6]) + ("..." if len(doc.tags) > 6 else ""),
        )
    console.print(table)


def load_chunk_index(
    session: Any, paths: Sequence[str]
) -> dict[str, list[tuple[str, int | None, int | None]]]:
    """Load the normalized chunk texts of the given document paths.

    Args:
        session: An open SQLAlchemy session.
        paths: Rel paths of the documents to index.

    Returns:
        ``{path: [(normalized_chunk_text, page, slide), ...]}`` in ordinal
        order; paths without a current document are absent.
    """
    if not paths:
        return {}
    rows = session.execute(
        select(File.rel_path, Document.latest_version_id)
        .join(Document, Document.current_file_id == File.id)
        .where(Document.status == "current", File.rel_path.in_(list(paths)))
    ).all()
    version_by_path = {path: version_id for path, version_id in rows}
    version_ids = sorted(set(version_by_path.values()))
    path_by_version = {version_id: path for path, version_id in version_by_path.items()}
    index: dict[str, list[tuple[str, int | None, int | None]]] = defaultdict(list)
    if version_ids:
        chunk_rows = session.execute(
            select(Chunk.document_version_id, Chunk.text, Chunk.page, Chunk.slide)
            .where(Chunk.document_version_id.in_(version_ids))
            .order_by(Chunk.document_version_id, Chunk.ordinal)
        ).all()
        for version_id, text, page, slide in chunk_rows:
            path = path_by_version.get(version_id)
            if path is not None:
                index[path].append((normalize_key(text), page, slide))
    return dict(index)


def answer_match(
    answer: str, chunks: Sequence[tuple[str, int | None, int | None]]
) -> tuple[float, int | None]:
    """Trace a reference answer inside a document's chunks.

    Args:
        answer: The reference answer text (may be empty).
        chunks: ``(normalized_text, page, slide)`` tuples of one document.

    Returns:
        ``(score, page_label)``: 1.0 when the normalized answer appears
        verbatim in some chunk (ignoring punctuation), else the best
        word-containment ratio and the page/slide of the best chunk (``None``
        when the answer is empty).

    Words are compared without punctuation, so a comma-separated answer
    ("Global, Statistics") matches a Markdown table cell ("| Global |").
    """
    answer_key = normalize_key(answer)
    if not answer_key:
        return 0.0, None
    answer_words = _WORD.findall(answer_key)
    tokens = set(answer_words)
    phrase = f" {' '.join(answer_words)} "
    best_score, best_label = 0.0, None
    for chunk_key, page, slide in chunks:
        label = page if page is not None else slide
        if answer_key in chunk_key:
            return 1.0, label
        if not tokens:  # punctuation-only answer (e.g. Markdown ":---:"): verbatim only
            continue
        chunk_words = _WORD.findall(chunk_key)
        if phrase in f" {' '.join(chunk_words)} ":
            return 1.0, label
        containment = len(tokens & set(chunk_words)) / len(tokens)
        if containment > best_score:
            best_score, best_label = containment, label
    return best_score, best_label


_WORD = re.compile(r"\w+")


VERIFY_OK = 1.0
VERIFY_PARTIAL = 0.6


def verify_questions(path: Path) -> None:
    """Check every question of a golden-set file against the indexed chunks.

    For each question with ``expected_docs`` the reference answer is traced in
    the expected document's chunks (verbatim or token overlap) and, when set,
    ``expected_pages`` is compared against the matching chunk's page/slide.

    Args:
        path: The golden-set YAML to verify.
    """
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    questions = data.get("questions") or []
    with session_scope() as session:
        chunk_index = load_chunk_index(
            session, [q["expected_docs"][0] for q in questions if q.get("expected_docs")]
        )
    table = Table(title=f"verify {path} ({len(questions)} questions)")
    for column in ("id", "verdict", "score", "page", "expected_pages", "question"):
        table.add_column(column, overflow="fold")
    counts: Counter[str] = Counter()
    for question in questions:
        expected = question.get("expected_docs") or []
        if not expected:
            counts["no-answer"] += 1
            continue
        chunks = chunk_index.get(expected[0])
        if chunks is None:
            counts["missing-doc"] += 1
            table.add_row(
                question["id"], "[red]missing-doc[/]", "-", "-", "-", question["question"][:60]
            )
            continue
        score, label = answer_match(question.get("reference_answer") or "", chunks)
        verdict = "ok" if score >= VERIFY_OK else ("partial" if score >= VERIFY_PARTIAL else "weak")
        counts[verdict] += 1
        color = "green" if verdict == "ok" else ("yellow" if verdict == "partial" else "red")
        pages = question.get("expected_pages") or []
        page_note = f"found p{label}" if label is not None else ""
        pages_note = f"p{pages}" if pages else ""
        if pages and label is not None and label not in pages:
            page_note += " MISMATCH"
        table.add_row(
            question["id"],
            f"[{color}]{verdict}[/]",
            f"{score:.2f}",
            page_note,
            pages_note,
            question["question"][:60],
        )
    console.print(table)
    console.print_json(json.dumps(dict(sorted(counts.items()))))


def draft(n_target: int, out: Path, workers: int, seed: int) -> None:
    """Draft the golden-set questions and write the review YAML.

    Args:
        n_target: Target number of draft questions.
        out: Output YAML path.
        workers: Parallel LLM drafting calls.
        seed: Seed for the stratified document pick.

    Raises:
        SystemExit: When no document could be drafted at all.
    """
    rng = random.Random(seed)
    with session_scope() as session:
        docs = collect_documents(session)
        eligible = [
            doc
            for doc in docs
            if doc.n_chunks and doc.token_count >= MIN_DOC_TOKENS and doc.lang_bucket != "unknown"
        ]
        n_main = max(0, n_target - N_TAG_FILTERED - N_NO_ANSWER)
        n_docs = max(1, math.ceil(n_main / EXPECTED_Q_PER_DOC))
        picked = stratified_pick(
            eligible, n_docs, rng, key=lambda d: (d.folder, d.format, d.lang_bucket)
        )
        cross = assign_cross_lingual(picked)
        picked_ids = {doc.doc_id for doc in picked}
        tagged = [doc for doc in eligible if doc.tags and doc.doc_id not in picked_ids]
        tag_picked = stratified_pick(tagged, N_TAG_FILTERED, rng, key=lambda d: d.tags[0])
        chunk_map = load_chunks(session, [*picked, *tag_picked])

    if not picked:
        raise SystemExit("No eligible documents to draft from - is the corpus indexed?")

    chat = get_chat("extract")
    jobs: list[tuple[DocInfo, str | None, bool]] = [
        (doc, cross.get(doc.doc_id), False) for doc in picked
    ] + [(doc, None, True) for doc in tag_picked]
    results: dict[int, tuple[list[dict[str, Any]], str | None]] = {}
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {
            pool.submit(
                draft_document, chat, chunk_map.get(doc.doc_id, []), doc, cross_lang, tag_pick
            ): doc
            for doc, cross_lang, tag_pick in jobs
        }
        for future in as_completed(futures):
            doc = futures[future]
            rows, error = future.result()
            results[doc.doc_id] = (rows, error)
            if error:
                logger.warning("%s: skipped (%s)", doc.path, error)
            else:
                logger.info("%s: %d question(s) drafted", doc.path, len(rows))

    questions: list[dict[str, Any]] = []
    failed = 0
    for doc, _, _ in jobs:
        rows, error = results.get(doc.doc_id, ([], "no result"))
        if error:
            failed += 1
        questions.extend(rows)
    questions.extend(draft_no_answer(chat, [f"{d.path} - {d.title or ''}" for d in docs]))

    if failed == len(jobs):
        raise SystemExit("Every document draft failed - check the chat endpoint configuration.")
    write_draft(
        out,
        questions,
        {
            "target_questions": n_target,
            "documents_drafting": len(picked),
            "documents_failed": failed,
            "seed": seed,
            "cross_lingual": sorted(cross.values()),
        },
    )


def main() -> None:
    """Parse arguments and run the requested mode."""
    logging.basicConfig(level=logging.WARNING)
    logging.getLogger(__name__).setLevel(logging.INFO)
