"""Windows Task Scheduler backend (PLAN.md §7.8).

The worker runs at logon as a scheduled task created through PowerShell's
``Register-ScheduledTask`` (restart on failure, no execution time limit). The
action runs the project venv's ``pythonw.exe`` directly so no console window
appears; logs go to ``%LOCALAPPDATA%\\mynotes\\Logs\\worker.log`` because the
install script sets ``MYNOTES_LOG_FILE`` as a user environment variable and
:func:`mynotes.logging_setup.configure_logging` honours it. For an always-on
team server, wrap the same command in a real Windows service via WinSW or
NSSM (documented in ``docs/infrastructure.md``, not generated here).
"""

from __future__ import annotations

import logging
import subprocess

from mynotes.platform.service import ServiceError, ServiceSpec

logger = logging.getLogger(__name__)

_INSTALL_COMMAND = "powershell -NoProfile -Command <script>"


def ps_quote(value: str) -> str:
    """Quote ``value`` as a single-quoted PowerShell string literal.

    Args:
        value: A path or argument for the generated script.

    Returns:
        The value wrapped in single quotes with embedded quotes doubled.
    """
    return "'" + value.replace("'", "''") + "'"


def render_script(spec: ServiceSpec) -> str:
    """Render the PowerShell script that registers the scheduled task.

    Args:
        spec: The service definition; ``MYNOTES_LOG_FILE`` is defaulted to
            ``<log_dir>/worker.log`` when the spec does not set it.

    Returns:
        The complete script text: user-level environment variables, the task
        action/trigger/settings and the ``Register-ScheduledTask`` call.
    """
    env = dict(spec.env)
    env.setdefault("MYNOTES_LOG_FILE", str(spec.log_dir / spec.log_name))
    lines = [
        f"# Generated by 'mynotes service install'; runs the mynotes {spec.component} at logon.",
        *(
            f"[Environment]::SetEnvironmentVariable({ps_quote(key)}, {ps_quote(value)}, 'User')"
            for key, value in sorted(env.items())
        ),
        (
            f"$action = New-ScheduledTaskAction -Execute {ps_quote(spec.exec_args[0])} "
            f"-Argument {ps_quote(' '.join(spec.exec_args[1:]))} "
            f"-WorkingDirectory {ps_quote(str(spec.working_dir))}"
        ),
        "$trigger = New-ScheduledTaskTrigger -AtLogOn",
        (
            "$settings = New-ScheduledTaskSettingsSet -RestartCount 3 "
            "-RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit 0"
        ),
        (
            f"Register-ScheduledTask -TaskName {ps_quote(spec.name)} "
            "-Action $action -Trigger $trigger -Settings $settings"
        ),
    ]
    return "\n".join(lines) + "\n"


class WindowsTaskBackend:
    """Install the worker as a logon-triggered scheduled task."""

    def render(self, spec: ServiceSpec) -> dict[str, str]:
        """Return the PowerShell install script under a command description."""
        return {_INSTALL_COMMAND: render_script(spec)}

    def install(self, spec: ServiceSpec) -> None:
        """Run the rendered script with ``powershell -NoProfile -Command``.

        Args:
            spec: The service definition.

        Raises:
            ServiceError: When the script exits non-zero.
        """
        result = self._powershell(render_script(spec))
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            raise ServiceError(f"Register-ScheduledTask failed: {detail}")
        logger.info("registered scheduled task %s", spec.name)

    def uninstall(self, spec: ServiceSpec) -> None:
        """Unregister the scheduled task without a confirmation prompt.

        Args:
            spec: The service definition.

        Raises:
            ServiceError: When ``Unregister-ScheduledTask`` fails.
        """
        command = f"Unregister-ScheduledTask -Confirm:$false -TaskName {ps_quote(spec.name)}"
        result = self._powershell(command)
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            raise ServiceError(f"Unregister-ScheduledTask failed: {detail}")

    def status(self, spec: ServiceSpec) -> str:
        """Return the task state from ``Get-ScheduledTask``."""
        command = f"Get-ScheduledTask -TaskName {ps_quote(spec.name)} | Select-Object State"
        result = self._powershell(command)
        output = (result.stdout or "").strip()
        if result.returncode != 0 and not output:
            detail = (result.stderr or "").strip()
            if "Cannot find" in detail or "No MSFT_Task" in detail:
                return "not installed"
            return detail[:200] or "unknown"
        return output or "unknown"

    def logs_hint(self, spec: ServiceSpec) -> str:
        """Return the ``Get-Content -Wait`` command that tails the worker log."""
        return f"Get-Content -Wait '{(spec.log_dir / spec.log_name)}'"

    def hints(self, spec: ServiceSpec) -> list[str]:
        """Return post-install guidance (none needed on Windows)."""
        return []

    @staticmethod
    def _powershell(script: str) -> subprocess.CompletedProcess[str]:
        """Run ``powershell -NoProfile -Command`` with the given script.

        Raises:
            ServiceError: When the ``powershell`` binary itself is missing.
        """
        try:
            return subprocess.run(
                ["powershell", "-NoProfile", "-Command", script],
                capture_output=True,
                text=True,
                check=False,
            )
        except FileNotFoundError as exc:
            raise ServiceError("powershell was not found; is this Windows?") from exc
